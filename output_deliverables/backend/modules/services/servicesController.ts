const ensureSeeded = async () => {
  const catCount = await ServiceCategory.countDocuments();
  if (catCount === 0) {
    for (const c of SEED_CATEGORIES) {
      await ServiceCategory.create({
        categoryId: c.categoryId,
        slug: c.slug,
        name: c.name,
        icon: c.icon,
        desc: c.desc,
        order: c.order,
      });

      for (let i = 0; i < c.services.length; i++) {
        const s = c.services[i];
        await ServiceItem.create({
          categoryId: c.categoryId,
          categorySlug: c.slug,
          slug: s.slug,
          name: s.name,
          sub: s.sub,
          icon: s.icon,
          image: s.image,
          order: i + 1,
          details: DEFAULT_DETAILS,
        });
      }
    }
  }
};

export const getServices = async (req: Request, res: Response) => {
  try {
    await ensureSeeded();
    const categories = await ServiceCategory.find().sort({ order: 1 });
    const items = await ServiceItem.find().sort({ categoryId: 1, order: 1 });

    const grouped = categories.map((cat: any) => ({
      ...cat.toObject(),
      services: items.filter((it: any) => it.categoryId === cat.categoryId),
    }));

    res.status(200).json({ success: true, data: grouped });
  } catch (error: any) {
    res.status(500).json({ success: false, message: error.message });
  }
};

export const getServiceBySlug = async (req: Request, res: Response) => {
  try {
    await ensureSeeded();
    const { slug } = req.params;
    const item = await ServiceItem.findOne({ slug });
    if (!item) {
      return res.status(404).json({ success: false, message: "Service not found" });
    }
    res.status(200).json({ success: true, data: item });
  } catch (error: any) {
    res.status(500).json({ success: false, message: error.message });
  }
};

export const createCategory = async (req: Request, res: Response) => {
  try {
    const newCat = await ServiceCategory.create(req.body);
    res.status(201).json({ success: true, data: newCat });
  } catch (error: any) {
    res.status(400).json({ success: false, message: error.message });
  }
};

export const updateCategory = async (req: Request, res: Response) => {
  try {
    const { id } = req.params;
    const updated = await ServiceCategory.findByIdAndUpdate(id, req.body, { new: true, runValidators: true });
    if (!updated) {
      return res.status(404).json({ success: false, message: "Category not found" });
    }
    res.status(200).json({ success: true, data: updated });
  } catch (error: any) {
    res.status(400).json({ success: false, message: error.message });
  }
};

export const deleteCategory = async (req: Request, res: Response) => {
  try {
    const { id } = req.params;
    const cat = await ServiceCategory.findByIdAndDelete(id);
    if (!cat) {
      return res.status(404).json({ success: false, message: "Category not found" });
    }
    await ServiceItem.deleteMany({ categoryId: cat.categoryId });
    res.status(200).json({ success: true, message: "Category and its services deleted" });
  } catch (error: any) {
    res.status(500).json({ success: false, message: error.message });
  }
};

export const createServiceItem = async (req: Request, res: Response) => {
  try {
    let payload = typeof req.body.data === "string" ? JSON.parse(req.body.data) : req.body;
    if (req.file) {
      const up = await uploadBuffer(req.file.buffer, "services");
      payload.image = { url: up.secure_url, publicId: up.public_id };
    }
    const created = await ServiceItem.create(payload);
    res.status(201).json({ success: true, data: created });
  } catch (error: any) {
    res.status(400).json({ success: false, message: error.message });
  }
};

export const updateServiceItem = async (req: Request, res: Response) => {
  try {
    const { id } = req.params;
    let payload = typeof req.body.data === "string" ? JSON.parse(req.body.data) : req.body;
    const existing = await ServiceItem.findById(id);
    if (!existing) {
      return res.status(404).json({ success: false, message: "Service item not found" });
    }

    if (req.file) {
      if (existing.image?.publicId && existing.image.publicId !== "default") {
        await deleteMedia(existing.image.publicId);
      }
      const up = await uploadBuffer(req.file.buffer, "services");
      payload.image = { url: up.secure_url, publicId: up.public_id };
    }

    const updated = await ServiceItem.findByIdAndUpdate(id, payload, { new: true, runValidators: true });
    res.status(200).json({ success: true, data: updated });
  } catch (error: any) {
    res.status(400).json({ success: false, message: error.message });
  }
};

